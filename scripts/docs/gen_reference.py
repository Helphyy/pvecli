def _ctx(cmd: Any) -> Any:
    # The click Context class vendored by Typer
    return type(cmd).make_context.__globals__["Context"](cmd)


def _subcommands(cmd: Any) -> list[tuple[str, Any]]:
    if not hasattr(cmd, "list_commands"):
        return []
    ctx = _ctx(cmd)
    return [(n, cmd.get_command(ctx, n)) for n in cmd.list_commands(ctx)]


def _markdown(text: str) -> str:
    """A docstring as Markdown: a list needs a blank line before it."""
    return re.sub(r"(?m)^(?!\s*$)(?!\s*(?:\d+\.|-) )(.+)\n(\s*(?:\d+\.|-) )", r"\1\n\n\2", text)


def _split_help(text: str | None) -> tuple[str, list[str]]:
    """Help text and the example command lines of a docstring."""
    text = (text or "").strip()
    match = re.search(r"^\s*Examples?:\s*$", text, flags=re.M)
    if not match:
        return _markdown(text), []
    body, examples = text[: match.start()].rstrip(), text[match.end():]
    # Dedent, so a continued command keeps its indentation
    lines = [ln.rstrip() for ln in textwrap.dedent(examples).splitlines() if ln.strip()]
    return _markdown(body), lines


def _summary(cmd: Any) -> str:
    return _cell(_split_help(cmd.help)[0].split("\n\n")[0]).rstrip(".")


def _type_name(param: Any) -> str:
    if getattr(param, "is_flag", False) or getattr(param, "is_bool_flag", False):
        return "flag"
    annotation = getattr(getattr(param, "type_descriptor", None), "annotation", None)
    if isinstance(annotation, type) and issubclass(annotation, enum.Enum):
        return " \\| ".join(f"`{m.value}`" for m in annotation)
    names = {str: "text", int: "integer", float: "number", Path: "path"}
    return names.get(annotation, "text") if isinstance(annotation, type) else "text"


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _option_cell(param: Any) -> str:
    main = [o for o in param.opts if o.startswith("--")] or param.opts
    short = [o for o in param.opts if not o.startswith("--")]
    kind = _type_name(param)
    hint = "" if kind == "flag" else " " + {"integer": "N", "number": "N", "path": "PATH"}.get(kind, "VALUE")
    # Short form first, like the help of most tools: -s, --storage VALUE
    cell = ", ".join([*(f"`{o}`" for o in short), f"`{main[0]}{hint}`"])
    if param.secondary_opts:
        cell += " / " + " ".join(f"`{o}`" for o in param.secondary_opts)
    return cell


def _default(param: Any) -> str:
    value = param.default
    if callable(value) or value is None or value == "":
        return ""
    if isinstance(value, enum.Enum):
        value = value.value
    if value is True and param.secondary_opts:
        return f"`{param.opts[0]}`"
    if value is False or value is True:
        return ""
    return f"`{value}`"


def _description(param: Any) -> str:
    desc = _cell(param.help or "").rstrip(".")
    kind = _type_name(param)
    if "`" in kind:  # choices
        desc += f". One of {kind}"
    return desc + "." if desc else ""


def _command_body(path: list[str], cmd: Any, level: int) -> list[str]:
    """Description, usage, options and examples of one command."""
    title = "pvecli " + " ".join(path)
    body, examples = _split_help(cmd.help)
    out = [body, ""] if body else []
    args = [p for p in cmd.params if type(p).__name__.endswith("Argument")]
    opts = [p for p in cmd.params if not type(p).__name__.endswith("Argument")
            and not getattr(p, "hidden", False) and p.name != "help"]
    usage = " ".join([title, *(f"[{p.name.upper()}]" if not p.required else p.name.upper() for p in args)])
    if opts:
        usage += " [OPTIONS]"
    out += ["```text", usage, "```", ""]
    if args:
        out += [f"{'#' * level} Arguments", "", "| Argument | Description |", "|:--|:--|"]
        out += [f"| `{p.name.upper()}` | {_description(p)} |" for p in args]
        out.append("")
    if opts:
        out += [f"{'#' * level} Options", ""]
        # A Default column only when an option of this command has one
        if any(_default(p) for p in opts):
            out += ["| Option | Default | Description |", "|:--|:--|:--|"]
            out += [f"| {_option_cell(p)} | {_default(p)} | {_description(p)} |" for p in opts]
        else:
            out += ["| Option | Description |", "|:--|:--|"]
            out += [f"| {_option_cell(p)} | {_description(p)} |" for p in opts]
        out.append("")
    if examples:
        out += [f"{'#' * level} Examples", "", "```bash", *examples, "```", ""]
    return out


def _front(title: str, description: str, icon: str | None = None) -> str:
    # JSON strings are valid YAML: a colon in a summary cannot break it
    head = f"title: {json.dumps(title)}\ndescription: {json.dumps(description)}\n"
    if icon:
        head = f"icon: {icon}\n" + head
    return f"---\n{head}---\n\n" + HEADER


def _command_page(path: list[str], cmd: Any) -> str:
    """One page: a command, or a subgroup with each of its commands."""
    title = "pvecli " + " ".join(path)
    lines = [f"# {title}", ""]
    subs = _subcommands(cmd)
    if not subs:
        lines += _command_body(path, cmd, 2)
    else:
        lines += [f"{_summary(cmd)}.", ""] + _sections(path, cmd, [])
    return _front(title, _summary(cmd) + ".") + "\n".join(lines).rstrip() + "\n"


def _sections(path: list[str], cmd: Any, rel: list[str]) -> list[str]:
    """One section per command, a nested group flattened: ## rule add."""
    out: list[str] = []
    for name, sub in _subcommands(cmd):
        here = [*rel, name]
        if _subcommands(sub):
            out += _sections([*path, name], sub, here)
        else:
            out += [f"## {' '.join(here)}", "", *_command_body([*path, name], sub, 3)]
    return out


def render() -> dict[str, str]:
    """Every reference page, by path under docs/cli/."""
    root = typer.main.get_command(__import__("src.cli.main", fromlist=["app"]).app)
    groups = dict(_subcommands(root))
    pages: dict[str, str] = {}
    index = ["# All commands", "",
             "Every command of pvecli, generated from the tool itself: `pvecli COMMAND -h` "
             "shows the same in the terminal.", ""]
    for section, _, names in SECTIONS:
        if not names:
            continue
        index += [f"## {section}", "", "| Command | What it does |", "|:--|:--|"]
        for name in names:
            cmd = groups[name]
            subs = _subcommands(cmd)
            if subs:
                lines = [f"# pvecli {name}", "", f"{_summary(cmd)}.", "",
                         "| Command | What it does |", "|:--|:--|"]
                lines += [f"| [`{sub}`]({sub}.md) | {_summary(c)}. |" for sub, c in subs]
                pages[f"{name}/index.md"] = _front(f"pvecli {name}", _summary(cmd) + ".") + "\n".join(lines) + "\n"
                for sub, c in subs:
                    pages[f"{name}/{sub}.md"] = _command_page([name, sub], c)
                index.append(f"| [`pvecli {name}`]({name}/index.md) | {_summary(cmd)}. |")
            else:
                pages[f"{name}.md"] = _command_page([name], cmd)
                index.append(f"| [`pvecli {name}`]({name}.md) | {_summary(cmd)}. |")
        index.append("")
    missing = set(groups) - {n for _, _, names in SECTIONS for n in names}
    if missing:
        raise SystemExit(f"Command groups in no section of SECTIONS: {', '.join(sorted(missing))}")
    # Listed beside the reference pages, which have an icon too
    pages["index.md"] = _front("All commands", "Every command of pvecli.", "lucide/square-terminal") + "\n".join(index).rstrip() + "\n"
    return pages


def _toml(value: str) -> str:
    return json.dumps(value)


def render_nav(pages: dict[str, str]) -> str:
    """The nav block of zensical.toml: sections, their pages, their commands."""
    root = typer.main.get_command(__import__("src.cli.main", fromlist=["app"]).app)
    groups = dict(_subcommands(root))
    out = [NAV_BEGIN, "nav = [", '  { "Home" = "index.md" },']
    for section, written, names in SECTIONS:
        # The index page of a section folder comes first and untitled, so
        # navigation.indexes attaches it to the tab (title from its front matter)
        present = [(title, path) for title, path in written
                   if (DOCS / path).exists() or path.startswith("cli/")]
        index = [p for _, p in present if p.endswith("/index.md") and not p.startswith("cli/")]
        refs = {p for _, p in present if p.startswith(("reference/", "cli/"))}
        entries = [f'    {_toml(p)},' for p in index]
        # Every list gets a heading: without one the sidebar starts with an
        # untitled list
        for heading, pages in (
            ("Guides", [(t, p) for t, p in present if p not in index and p not in refs]),
            ("Reference", [(t, p) for t, p in present if p in refs]),
        ):
            if pages:
                entries.append(f'    {{ {_toml(heading)} = [')
                # An index page listed plainly would become the index of the
                # heading itself (navigation.indexes): it gets a section of its own
                entries += [f'      {{ {_toml(t)} = [{_toml(p)}] }},' if p.endswith("index.md")
                            else f'      {{ {_toml(t)} = {_toml(p)} }},' for t, p in pages]
                entries.append("    ] },")
        if names:
            entries.append('    { "Commands" = [')
            for name in names:
                if _subcommands(groups[name]):
                    subs = [f'        {{ {_toml(sub)} = "cli/{name}/{sub}.md" }},' for sub, _ in _subcommands(groups[name])]
                    entries.append(f'      {{ {_toml(name)} = ["cli/{name}/index.md",')
                    entries += subs
                    entries.append("      ] },")
                else:
                    entries.append(f'      {{ {_toml(name)} = "cli/{name}.md" }},')
            entries.append("    ] },")
        if entries:
            out += [f"  {{ {_toml(section)} = ["] + entries + ["  ] },"]
    out += ["]", NAV_END]
    return "\n".join(out)


def _with_nav(config: str, nav: str) -> str:
    start, end = config.find(NAV_BEGIN), config.find(NAV_END)
    if start < 0 or end < 0:
        raise SystemExit(f"zensical.toml has no generated nav block ({NAV_BEGIN!r} ... {NAV_END!r})")
    return config[:start] + nav + config[end + len(NAV_END):]


def main() -> int:
    pages = render()
    config = CONFIG.read_text()
    new_config = _with_nav(config, render_nav(pages))
    if "--check" in sys.argv:
        stale = [n for n, text in pages.items()
                 if not (OUT / n).exists() or (OUT / n).read_text() != text]
        stale += [str(p.relative_to(OUT)) for p in OUT.rglob("*.md") if str(p.relative_to(OUT)) not in pages]
        if new_config != config:
            stale.append("zensical.toml nav")
        if stale:
            print("Out of date: " + ", ".join(sorted(stale)) + ". Run: python -m scripts.docs.gen_reference")
            return 1
        return 0
    for old in OUT.rglob("*.md"):
        if str(old.relative_to(OUT)) not in pages:
            old.unlink()
    for name, text in pages.items():
        (OUT / name).parent.mkdir(parents=True, exist_ok=True)
        (OUT / name).write_text(text)
    CONFIG.write_text(new_config)
    print(f"{len(pages)} pages written to {OUT.relative_to(ROOT)}, nav updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
