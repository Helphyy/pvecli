"""Generate the command reference and the navigation of the documentation.

The reference comes from the Typer application itself: one page per
command under docs/cli/GROUP/, so it cannot drift from the code. The
navigation of zensical.toml is written here too, from SECTIONS: the guides
of each domain, then the commands of that domain, like Exegol's docs (a
product, its pages, then its command line, one page per command).

    python -m scripts.docs.gen_reference           # write the pages and the nav
    python -m scripts.docs.gen_reference --check   # exit 1 when out of date

tests/static/test_docs_site.py fails when either is out of date.
"""

